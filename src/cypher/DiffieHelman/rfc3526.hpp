/**
возврат: [prime, generator]
 */
inline auto get_dh_params(const std::string& p, const std::string& g)
    -> std::tuple<BI, BI> {
  if (g.empty() || p.empty()) {
    throw std::runtime_error("empty DH params");
  }
  if (p.size() < 2 || !p.starts_with("0x")) {
    throw std::runtime_error("prime string not hex");
  }
  if (g.size() < 2 || !g.starts_with("0x")) {
    throw std::runtime_error("generator string not hex");
  }
  BI prime(p.c_str());
  BI generator(g.c_str());

  return {std::move(prime), std::move(generator)};
}

inline auto get_dh(const BI& p, const BI& g) -> meow::cypher::DiffieHelman {
  return {p, g};
}

inline auto get_dh() -> meow::cypher::DiffieHelman {
  const auto [prime, gen] =
      get_dh_params(DH_STANDART_P_str_hex, DH_STANDART_G_str_hex);
  return {prime, gen};
}
